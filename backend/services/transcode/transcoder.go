// TranscoderService handles video processing and CMAF HLS ladder generation.
type TranscoderService struct {
	db        *sql.DB
	baseDir   string
	hlsDir    string
	masterDir string
}

var DefaultTranscoder *TranscoderService

// InitTranscoder initializes storage directories and the global transcoder service.
func InitTranscoder() error {
	baseDir := "data"
	masterDir := filepath.Join(baseDir, "masters")
	hlsDir := filepath.Join(baseDir, "hls")

	if err := os.MkdirAll(masterDir, 0755); err != nil {
		return fmt.Errorf("creating masters directory: %w", err)
	}
	if err := os.MkdirAll(hlsDir, 0755); err != nil {
		return fmt.Errorf("creating hls directory: %w", err)
	}

	DefaultTranscoder = &TranscoderService{
		db:        database.DB,
		baseDir:   baseDir,
		hlsDir:    hlsDir,
		masterDir: masterDir,
	}

	log.Printf("[Transcoder] ✓ Transcoder initialized (Masters: %s, HLS: %s)", masterDir, hlsDir)
	return nil
}

// MasterFilePath returns the local filepath for a master video file.
func (s *TranscoderService) MasterFilePath(videoID string) string {
	return filepath.Join(s.masterDir, videoID+".mp4")
}

// HLSDirPath returns the local directory for transcoded HLS chunks.
func (s *TranscoderService) HLSDirPath(videoID string) string {
	return filepath.Join(s.hlsDir, videoID)
}

// StartTranscodeJob spawns an asynchronous background worker to probe and transcode the video.
func (s *TranscoderService) StartTranscodeJob(videoID string) {
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Minute)
		defer cancel()

		if err := s.ExecuteJob(ctx, videoID); err != nil {
			log.Printf("[Transcoder] ❌ Job failed for video %s: %v", videoID, err)
			s.updateVideoStatus(videoID, "failed", err.Error(), 0)
		}
	}()
}

// ExecuteJob performs the complete probe, ladder filtering, and FFmpeg fMP4 CMAF transcode.
func (s *TranscoderService) ExecuteJob(ctx context.Context, videoID string) error {
	masterPath := s.MasterFilePath(videoID)
	if _, err := os.Stat(masterPath); err != nil {
		return fmt.Errorf("master video file does not exist: %w", err)
	}

	// 1. Mark video as processing
	s.updateVideoStatus(videoID, "processing", "", 0)

	startTime := time.Now()
	log.Printf("[Transcoder] ▶ Starting CMAF HLS transcoding for Video: %s", videoID)

	// 2. Probe video metadata
	meta, err := ProbeVideo(ctx, masterPath)
	if err != nil {
		log.Printf("[Transcoder] Probe warning: %v. Using fallback 1080p profile.", err)
		meta = VideoMetadata{
			Width:    1920,
			Height:   1080,
			Duration: 60.0,
			FPS:      25.0,
		}
	}
	log.Printf("[Transcoder] Video %s probed: %dx%d @ %.2f fps, duration: %.2fs",
		videoID, meta.Width, meta.Height, meta.FPS, meta.Duration)

	// 3. Filter ABR ladder
	rungs := FilterLadder(meta)
	log.Printf("[Transcoder] Video %s generated %d ABR ladder rungs", videoID, len(rungs))

	// 4. Create destination directory
	outputDir := s.HLSDirPath(videoID)
	_ = os.RemoveAll(outputDir)
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("creating HLS output directory: %w", err)
	}

	// 5. Execute FFmpeg
	ffmpegBin := GetFFmpegPath()
	ffmpegArgs := BuildFFmpegHLSCommand(masterPath, outputDir, meta, rungs)

	log.Printf("[Transcoder] Executing: %s %s", ffmpegBin, strings.Join(ffmpegArgs, " "))
	cmd := exec.CommandContext(ctx, ffmpegBin, ffmpegArgs...)
	var stderrBuf bytes.Buffer
	cmd.Stderr = &stderrBuf

	if err := cmd.Run(); err != nil {
		stderrMsg := stderrBuf.String()
		if len(stderrMsg) > 1000 {
			stderrMsg = stderrMsg[len(stderrMsg)-1000:]
		}
		// If FFmpeg is not available on local path, create single-file direct playlist fallback
		if strings.Contains(err.Error(), "executable file not found") || strings.Contains(err.Error(), "cannot find") {
			log.Printf("[Transcoder] FFmpeg executable not found. Operating in direct-stream mode.")
			hlsURL := fmt.Sprintf("/api/playback/%s/master.m3u8", videoID)
			s.createDirectFallbackPlaylist(outputDir, videoID)
			s.updateVideoHLS(videoID, "ready", outputDir, hlsURL, meta.Duration)
			return nil
		}
		return fmt.Errorf("FFmpeg transcode failed: %w | Stderr: %s", err, stderrMsg)
	}

	// 6. Verify master.m3u8
	masterM3U8 := filepath.Join(outputDir, "master.m3u8")
	if _, err := os.Stat(masterM3U8); err != nil {
		return fmt.Errorf("master.m3u8 was not generated by FFmpeg: %w", err)
	}

	hlsURL := fmt.Sprintf("/api/playback/%s/master.m3u8", videoID)
	if err := s.updateVideoHLS(videoID, "ready", outputDir, hlsURL, meta.Duration); err != nil {
		return fmt.Errorf("updating video record: %w", err)
	}

	log.Printf("[Transcoder] ★ Video %s successfully transcoded in %v (CMAF HLS Ready at %s)",
		videoID, time.Since(startTime), hlsURL)
	return nil
}

func (s *TranscoderService) updateVideoStatus(videoID, status, errMsg string, durationSec float64) {
	now := time.Now()
	query := "UPDATE videos SET transcode_status = ?, updated_at = ? WHERE id = ?"
	_, _ = database.DB.Exec(query, status, now, videoID)
}

func (s *TranscoderService) updateVideoHLS(videoID, status, hlsPath, hlsURL string, durationSec float64) error {
	now := time.Now()
	durationMins := durationSec / 60.0
	if durationMins <= 0 {
		durationMins = 2.0
	}

	query := `
		UPDATE videos 
		SET transcode_status = ?, hls_path = ?, hls_url = ?, duration_minutes = ?, updated_at = ?
		WHERE id = ?
	`
	_, err := database.DB.Exec(query, status, hlsPath, hlsURL, durationMins, now, videoID)
	return err
}

func (s *TranscoderService) createDirectFallbackPlaylist(outputDir, videoID string) {
	content := fmt.Sprintf(`#EXTM3U
#EXT-X-VERSION:7
#EXT-X-STREAM-INF:BANDWIDTH=5000000,RESOLUTION=1920x1080,CODECS="avc1.640028,mp4a.40.2"
/data/masters/%s.mp4
`, videoID)
	_ = os.WriteFile(filepath.Join(outputDir, "master.m3u8"), []byte(content), 0644)
}
